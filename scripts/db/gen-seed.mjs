// Generates supabase/seed.sql from the app's seed catalogue so the database
// and demo mode always start from the same products, coupons and settings.
// Run: npm run db:seed   (Node 24+ loads the TypeScript catalogue directly)
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { buildSeedCoupons, buildSeedProducts, categories, defaultSettings } from "../../src/lib/data/catalog.ts";

const out = fileURLToPath(new URL("../../supabase/seed.sql", import.meta.url));

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const arr = (list) => (list.length ? `array[${list.map(q).join(", ")}]::text[]` : "'{}'::text[]");
const json = (v) => `${q(JSON.stringify(v))}::jsonb`;
const productId = (slug) => `md5(${q(`ritan:product:${slug}`)})::uuid`;
const variantId = (slug, weight) => `md5(${q(`ritan:variant:${slug}:${weight}`)})::uuid`;

const lines = [
  "-- Generated by scripts/db/gen-seed.mjs from src/lib/data/catalog.ts. Do not edit by hand.",
  "-- Placeholder prices and stock: update them from the admin dashboard before launch.",
  "",
  "begin;",
  "",
  "insert into public.categories (id, name, blurb, sort) values",
  categories.map((c) => `  (${q(c.id)}, ${q(c.name)}, ${q(c.blurb)}, ${c.sort})`).join(",\n") + "\non conflict (id) do nothing;",
  "",
];

for (const p of buildSeedProducts()) {
  lines.push(
    `insert into public.products (id, slug, name, alt_name, category_id, tagline, summary, description, key_ingredients, ingredients, how_to_use, pack_type, image, image_width, image_height, palette, sprites, featured, is_active, sort) values (`,
    `  ${productId(p.slug)}, ${q(p.slug)}, ${q(p.name)}, ${q(p.altName)}, ${q(p.categoryId)},`,
    `  ${q(p.tagline)},`,
    `  ${q(p.summary)},`,
    `  ${q(p.description)},`,
    `  ${arr(p.keyIngredients)}, ${q(p.ingredients)},`,
    `  ${q(p.howToUse)},`,
    `  ${q(p.packType)}, ${q(p.image)}, ${p.imageWidth}, ${p.imageHeight},`,
    `  ${json(p.palette)}, ${arr(p.sprites)}, ${p.featured}, ${p.isActive}, ${p.sort}`,
    `) on conflict (slug) do nothing;`,
    `insert into public.product_variants (id, product_id, weight_g, sku, price_paise, mrp_paise, stock, is_active) values`,
    p.variants
      .map((v) => `  (${variantId(p.slug, v.weightG)}, ${productId(p.slug)}, ${v.weightG}, ${q(v.sku)}, ${v.price}, ${v.mrp ?? "null"}, ${v.stock}, ${v.isActive})`)
      .join(",\n") + "\non conflict (product_id, weight_g) do nothing;",
    "",
  );
}

lines.push(
  "insert into public.coupons (code, description, type, value, min_subtotal_paise, max_discount_paise, starts_at, ends_at, usage_limit, per_customer_limit, is_active) values",
  buildSeedCoupons()
    .map(
      (c) =>
        `  (${q(c.code)}, ${q(c.description)}, ${q(c.type)}, ${c.value}, ${c.minSubtotal}, ${c.maxDiscount ?? "null"}, ${q(c.startsAt)}, ${q(c.endsAt)}, ${c.usageLimit ?? "null"}, ${c.perCustomerLimit ?? "null"}, ${c.isActive})`,
    )
    .join(",\n") + "\non conflict (code) do nothing;",
  "",
  `insert into public.settings (key, value) values ('store', ${json(defaultSettings)})`,
  "on conflict (key) do nothing;",
  "",
  "commit;",
  "",
  "-- After the store owner signs up on the website, give that account admin access:",
  "-- update public.profiles set role = 'admin' where email = '<owner email>';",
  "",
);

writeFileSync(out, lines.join("\n"));
console.log(`Wrote ${out}`);
